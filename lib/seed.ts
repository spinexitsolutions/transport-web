const daysAgo = (d: number, h = 10) => {
  const t = new Date("2026-11-01T00:00:00+05:30");
  t.setDate(t.getDate() - d);
  t.setHours(h, (d * 17) % 60);
  return t.toISOString();
};

const daysAhead = (d: number) => {
  const t = new Date("2026-11-01T18:00:00+05:30");
  t.setDate(t.getDate() + d);
  return t.toISOString();
};

function mkShipment(
  id: string,
  customer: string,
  service: string,
  route: string[],
  upTo: ShipmentStatus,
  startDaysAgo: number,
  weight: number,
  pieces: number,
  etaIn: number,
): Shipment {
  const flow: ShipmentStatus[] = ["booked", "picked", "in_transit", "customs", "out_for_delivery", "delivered"];
  const idx = flow.indexOf(upTo);
  const notes: Record<ShipmentStatus, string> = {
    booked: "Shipment booked & documents verified",
    picked: "Picked up from shipper",
    in_transit: "Departed hub — moving on schedule",
    customs: "Cleared customs & compliance checks",
    out_for_delivery: "Out for delivery with Kinetik crew",
    delivered: "Delivered & signed by consignee",
    exception: "Delayed — weather advisory",
  };
  const events: ShipmentEvent[] = flow.slice(0, idx + 1).map((s, i) => ({
    id: `${id}-e${i}`,
    status: s,
    location: route[Math.min(i, route.length - 1)],
    note: notes[s],
    at: daysAgo(Math.max(startDaysAgo - i, 0), 8 + i * 2),
  }));
  return {
    id,
    customer,
    service,
    origin: route[0],
    destination: route[route.length - 1],
    weight,
    pieces,
    status: upTo,
    eta: upTo === "delivered" ? events[events.length - 1].at : daysAhead(etaIn),
    createdAt: events[0].at,
    events: events.reverse(),
  };
}

